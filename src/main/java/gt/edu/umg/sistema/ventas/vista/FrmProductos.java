    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        Producto producto = new Producto();
        
        producto.setIdProducto(Integer.parseInt(textIDProducto.getText()));
        
        producto.setNombre(textNombre.getText());
        
        producto.setDescripcion(textDescripcion.getText());
        
        producto.setPrecio(Double.parseDouble(textPrecio.getText()));
        
        producto.setStock(Integer.parseInt(textStock.getText()));
        
        controller.guardar(producto);
        
        JOptionPane.showMessageDialog(
                 this,
                 "Producto guardado correctamente.");
        
        limpiarCampos();
        cargarTabla();
    }//GEN-LAST:event_btnGuardarActionPerformed

