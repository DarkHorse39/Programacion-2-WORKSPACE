    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblDetalleFactura.getSelectedRow();
        
        if (fila == -1) {
            JOptionPane.showMessageDialog(
                    this, "seleccione una fila."
            );
            
            return;
        }
        
        DefaultTableModel modelo = 
                (DefaultTableModel) tblDetalleFactura.getModel();
        
        modelo.removeRow(fila);
        
        calcularTotal();
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
       try {
        
        Factura factura = new Factura();

        factura.setNumeroFactura(
                txtNumeroFactura.getText());

        factura.setFecha(
                txtFecha.getText());

        factura.setCliente(
                txtCliente.getText());

        factura.setNit(
                txtNIT.getText());

        double total = Double.parseDouble(
                lblTotal.getText()
                        .replace("Q", "")
                        .trim());

        factura.setTotal(total);
        
        int idFactura =
                controller.guardar(factura);
        
        guardarDetalles(idFactura);

        JOptionPane.showMessageDialog(
                this,
                "Factura guardada correctamente."
        );
        
        limpiarFormulario();

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage());
       }
    }//GEN-LAST:event_btnGuardarActionPerformed
    
    
    private void limpiarFormulario() {

    textIdFactura.setText("");
    txtNumeroFactura.setText("");
    txtFecha.setText("");
    txtCliente.setText("");
    txtNIT.setText("");

    DefaultTableModel modelo =
            (DefaultTableModel) tblDetalleFactura.getModel();

    modelo.setRowCount(0);

    lblTotal.setText("Q 0.00");
    
    tblDetalleFactura.setModel(
    new DefaultTableModel(
        new Object[][]{},
        new String[]{
            "Producto",
            "Cantidad",
            "Precio",
            "Descripcion",
            "Subtotal"
        }
     )
   );
  }
    
    
    private void guardarDetalles(
            int idFactura) {
        
        for (int i = 0;
                i < tblDetalleFactura.getRowCount();
                i++) {
            Object idProducto = 
                    tblDetalleFactura.getValueAt(i, 0);
            
            Object producto = 
                    tblDetalleFactura.getValueAt(i, 1);
            
            Object cantidad =
                    tblDetalleFactura.getValueAt(i, 2);
            
            Object precio =
                    tblDetalleFactura.getValueAt(i, 3);
            
            Object descripcion =
                    tblDetalleFactura.getValueAt(i, 4);
            
            Object subtotal =
                    tblDetalleFactura.getValueAt(i, 5);
            
            if (producto == null) {
                continue;
            }
            
            DetalleFactura detalle = 
                    new DetalleFactura();
            
            detalle.setIdProducto(
                    Integer.parseInt(
                            idProducto.toString()
                    )
            );
            
            detalle.setIdFactura(idFactura);
            
            detalle.setProducto(
                    producto.toString());
            
            detalle.setCantidad(
                    Integer.parseInt(
                            cantidad.toString()));
            
            detalle.setPrecio(
                    Double.parseDouble(
                           precio.toString()));
            
            detalle.setDescripcion(
                    descripcion.toString());
            
            detalle.setSubtotal(
                    Double.parseDouble(
                            subtotal.toString()));
            
            detalleDAO.guardar(detalle);
            
            ProductoDAOImpl productoDAO =
                    new ProductoDAOImpl();
            
            productoDAO.descontarStock(
                    detalle.getIdProducto(),
                    detalle.getCantidad());
        }
    }

