private void calcularTotal(){
    double total = 0;
    
  for (int i = 0; i < tblDetalleFactura.getRowCount(); i++) {
      
      Object valor =
              tblDetalleFactura.getValueAt(i, 5);

      if (valor != null) {

          double subtotal =

                  Double.parseDouble(

                          valor.toString());

          total += subtotal;

      } 
    }
    
    lblTotal.setText(String.format("Q %.2f", total)
    );
}

